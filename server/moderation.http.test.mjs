import test from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {cpSync,mkdtempSync,rmSync} from 'node:fs';
import net from 'node:net';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {openStore} from './storage.mjs';

const source=path.dirname(fileURLToPath(import.meta.url));
const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));

test('rate limits posts and persists report, hide and restore with admin only',async t=>{
  const root=mkdtempSync(path.join(os.tmpdir(),'agent-guild-moderation-'));
  cpSync(source,path.join(root,'server'),{recursive:true});
  const listener=net.createServer();
  await new Promise(resolve=>listener.listen(0,'127.0.0.1',resolve));
  const port=listener.address().port;
  await new Promise(resolve=>listener.close(resolve));
  const origin=`http://127.0.0.1:${port}`;
  const child=spawn(process.execPath,['--import',path.join(root,'server','ownership.fixture.mjs'),path.join(root,'server','index.mjs')],{env:{...process.env,PORT:String(port),AGENT_GUILD_ORIGIN:origin,AGENT_GUILD_GITHUB_CLIENT_ID:'fixture-id',AGENT_GUILD_GITHUB_CLIENT_SECRET:'fixture-secret',AGENT_GUILD_ADMIN_IDS:'789',AGENT_GUILD_POST_LIMIT:'2',AGENT_GUILD_BLOCK_ISSUE_4:'1'},stdio:'ignore'});
  t.after(()=>{child.kill();rmSync(root,{recursive:true,force:true});});
  const request=(route,options={})=>fetch(origin+route,{redirect:'manual',...options});
  let ready=false;
  for(let i=0;i<100;i++){if(child.exitCode!==null)throw new Error('server exited');try{await request('/api/auth/me');ready=true;break;}catch{await sleep(20);}}
  assert.ok(ready);
  async function login(code){
    const start=await request('/api/auth/login');
    const state=new URL(start.headers.get('location')).searchParams.get('state');
    const oauthCookie=start.headers.getSetCookie()[0].split(';')[0];
    const callback=await request(`/api/auth/callback?code=${code}&state=${state}`,{headers:{Cookie:oauthCookie}});
    assert.equal(callback.status,302);
    const cookie=callback.headers.getSetCookie().find(x=>x.startsWith('ag_session=')).split(';')[0];
    const me=await (await request('/api/auth/me',{headers:{Cookie:cookie}})).json();
    return {cookie,csrf:me.csrfToken};
  }
  const alice=await login('alice'),bob=await login('bob'),admin=await login('charlie');
  const post=(route,user,value)=>request(route,{method:'POST',headers:{Cookie:user.cookie,'X-CSRF-Token':user.csrf,Origin:origin,'Content-Type':'application/json'},body:JSON.stringify(value)});
  const create=number=>post('/api/listings',alice,{issueUrl:`https://github.com/owner/repo/issues/${number}`,acceptance:'Fixture acceptance',aiPolicy:'poster_declared',aiEvidence:'Fixture evidence',amount:0});
  const first=await create(1);
  assert.equal(first.status,201);
  const id=(await first.json()).id;
  assert.equal((await create(3)).status,201);
  assert.equal((await create(4)).status,429);
  const answerRoute=`/api/listings/${id}/answers`;
  assert.equal((await post(answerRoute,bob,{text:'First completed answer'})).status,201);
  const second=await post(answerRoute,bob,{text:'Second completed answer'});
  assert.equal(second.status,201);
  const answerId=(await second.json()).answers[1].id;
  assert.equal((await post(answerRoute,bob,{text:'Third completed answer'})).status,429);
  assert.equal((await request('/api/reports',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({listingId:id,reason:'Spam report'})})).status,401);
  const reported=await post('/api/reports',bob,{listingId:id,answerId,reason:'The answer appears to be spam'});
  assert.equal(reported.status,201);
  assert.equal((await post('/api/reports',bob,{listingId:id,answerId,reason:'Repeated spam report'})).status,409);
  assert.equal((await post('/api/reports',bob,{listingId:id,reason:'The listing is also spam'})).status,201);
  assert.equal((await post('/api/reports',bob,{listingId:(await (await request('/api/listings')).json()).listings.find(x=>x.id!==id&&x.id!=='demo-cli-14647').id,reason:'Another listing report'})).status,429);
  assert.equal((await request('/api/moderation',{headers:{Cookie:bob.cookie}})).status,403);
  assert.equal((await post(`/api/moderation/${id}`,bob,{action:'hide',reason:'Confirmed spam content'})).status,403);
  const before=await (await request('/api/moderation',{headers:{Cookie:admin.cookie}})).json();
  assert.equal(before.reports.length,2);
  assert.equal(before.reports[0].reporterId,'456');
  assert.equal((await post(`/api/moderation/${id}`,admin,{action:'hide',reason:'Confirmed spam content'})).status,200);
  assert.equal((await post(`/api/moderation/${id}`,admin,{action:'hide',reason:'Repeated hide request'})).status,409);
  const hiddenList=await (await request('/api/listings')).json();
  assert.equal(hiddenList.listings.some(x=>x.id===id),false);
  assert.equal((await request(`/api/listings/${id}`)).status,404);
  assert.equal((await request(`/api/listings/${id}`,{headers:{Cookie:admin.cookie}})).status,200);
  assert.equal((await post(answerRoute,bob,{text:'Cannot answer hidden quest'})).status,403);
  assert.equal((await post(`/api/moderation/${id}`,admin,{action:'restore',reason:'False positive, restore'})).status,200);
  assert.equal((await (await request('/api/listings')).json()).listings.some(x=>x.id===id),true);
  const db=openStore(path.join(root,'data'));
  const state=db.read();
  db.close();
  assert.equal(state.reports.length,2);
  assert.deepEqual(state.moderationHistory.map(x=>x.action),['hide','restore']);
  assert.deepEqual(state.moderationHistory.map(x=>x.actorId),['789','789']);
  assert.equal(state.moderation[id].hidden,false);
});
